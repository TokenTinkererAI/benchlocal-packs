#!/usr/bin/env node
/**
 * build-dataset.mjs - vendor-check and compile the IFEval dataset.
 *
 * Source of truth: data/ifeval.jsonl, the verbatim `ifeval_input_data.jsonl`
 * from the HuggingFace dataset repo `google/IFEval` (Apache-2.0), whose 541
 * rows are the prompts used by the IFEval paper (Zhou et al. 2023,
 * arXiv:2311.07911).
 *
 * This script:
 *   1. re-reads data/ifeval.jsonl and enforces
 *        - exactly 541 records,
 *        - sha256 == the pinned SOURCE_SHA256 below (fails loudly otherwise),
 *        - every record has prompt / instruction_id_list / kwargs,
 *        - the id <-> kwargs length invariant (one kwargs entry per instruction);
 *   2. emits lib/generated/problems.ts: one entry per prompt with the pack id
 *      `IFEval/<index>` (0-based, file order), the prompt verbatim, the
 *      instruction ids and the JSON-safe kwargs.
 *
 * Usage: npm run build:dataset
 */

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_PATH = path.join(REPO_ROOT, "data", "ifeval.jsonl");
const OUT_PATH = path.join(REPO_ROOT, "lib", "generated", "problems.ts");

/** sha256 of data/ifeval.jsonl as downloaded from `hf download google/IFEval`. */
const SOURCE_SHA256 = "6a85310ca8ce15eff755aa08a3a4ff931c7e273e7515ebb3c492ea85fd8288f2";
const EXPECTED_COUNT = 541;

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

const raw = fs.readFileSync(SOURCE_PATH);
const actualSha = createHash("sha256").update(raw).digest("hex");
if (actualSha !== SOURCE_SHA256) {
  fail(
    `data/ifeval.jsonl sha256 mismatch:\n  expected ${SOURCE_SHA256}\n  actual   ${actualSha}\n` +
      "The vendored dataset changed - re-verify provenance before updating SOURCE_SHA256."
  );
}

const lines = raw.toString("utf8").split(/\r?\n/).filter((line) => line.trim() !== "");
if (lines.length !== EXPECTED_COUNT) {
  fail(`expected ${EXPECTED_COUNT} records in data/ifeval.jsonl, found ${lines.length}`);
}

const records = lines.map((line, index) => {
  let record;
  try {
    record = JSON.parse(line);
  } catch (error) {
    fail(`record ${index} is not valid JSON: ${error.message}`);
  }
  if (typeof record.prompt !== "string" || record.prompt.trim() === "") {
    fail(`record ${index} has no prompt`);
  }
  if (!Array.isArray(record.instruction_id_list) || record.instruction_id_list.length === 0) {
    fail(`record ${index} has no instruction_id_list`);
  }
  if (!Array.isArray(record.kwargs) || record.kwargs.length !== record.instruction_id_list.length) {
    fail(
      `record ${index} has ${Array.isArray(record.kwargs) ? record.kwargs.length : "no"} kwargs entries ` +
        `for ${record.instruction_id_list.length} instruction(s)`
    );
  }
  for (const instructionId of record.instruction_id_list) {
    if (typeof instructionId !== "string" || !instructionId.includes(":")) {
      fail(`record ${index} has a malformed instruction id: ${JSON.stringify(instructionId)}`);
    }
  }
  const kwargs = record.kwargs.map((entry, kwargIndex) => {
    if (entry === null || typeof entry !== "object" || Array.isArray(entry)) {
      fail(`record ${index} kwargs[${kwargIndex}] is not an object`);
    }
    const clean = {};
    for (const [key, value] of Object.entries(entry)) {
      const isScalar = typeof value === "string" || typeof value === "number";
      const isStringArray = Array.isArray(value) && value.every((item) => typeof item === "string");
      if (!isScalar && !isStringArray) {
        fail(
          `record ${index} kwargs[${kwargIndex}].${key} has unsupported type ` +
            `${Array.isArray(value) ? "array" : typeof value}`
        );
      }
      clean[key] = value;
    }
    return clean;
  });
  return {
    id: `IFEval/${index}`,
    key: typeof record.key === "number" ? record.key : index + 1000,
    prompt: record.prompt,
    instructionIds: record.instruction_id_list.map(String),
    kwargs
  };
});

const header = `/**
 * AUTO-GENERATED by scripts/build-dataset.mjs - do not edit by hand.
 *
 * Benchmark: IFEval (Zhou et al. 2023, arXiv:2311.07911).
 * Dataset:   google/IFEval on HuggingFace, file \`ifeval_input_data.jsonl\`
 *            (Apache-2.0), vendored verbatim as data/ifeval.jsonl.
 * Source sha256: ${SOURCE_SHA256}
 * Records: ${records.length} (ids IFEval/0 .. IFEval/${records.length - 1}, dataset file order)
 */

import type { IfevalProblem } from "../types";

export const DATASET_SHA256 = "${SOURCE_SHA256}";
export const PROBLEM_COUNT = ${records.length};

export const PROBLEMS: IfevalProblem[] = [
`;

const body = records
  .map((record) => {
    return (
      "  {\n" +
      `    id: ${JSON.stringify(record.id)},\n` +
      `    key: ${record.key},\n` +
      `    prompt: ${JSON.stringify(record.prompt)},\n` +
      `    instructionIds: ${JSON.stringify(record.instructionIds)},\n` +
      `    kwargs: ${JSON.stringify(record.kwargs)}\n` +
      "  },"
    );
  })
  .join("\n");

fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
fs.writeFileSync(OUT_PATH, `${header}${body}\n];\n`, "utf8");

// ---------------------------------------------------------------------------
// Report
// ---------------------------------------------------------------------------

const instructionCounts = new Map();
for (const record of records) {
  for (const instructionId of record.instructionIds) {
    instructionCounts.set(instructionId, (instructionCounts.get(instructionId) ?? 0) + 1);
  }
}
const multiInstruction = records.filter((record) => record.instructionIds.length > 1).length;

console.log(`source:        data/ifeval.jsonl`);
console.log(`source sha256: ${actualSha}`);
console.log(`records:       ${records.length}`);
console.log(`ids:           ${records[0].id} .. ${records[records.length - 1].id}`);
console.log(`instruction ids: ${instructionCounts.size} distinct`);
for (const [instructionId, count] of [...instructionCounts.entries()].sort()) {
  console.log(`  ${instructionId}: ${count}`);
}
console.log(`multi-instruction prompts: ${multiInstruction}`);
const outBytes = fs.statSync(OUT_PATH).size;
console.log(`wrote:         lib/generated/problems.ts (${(outBytes / 1024).toFixed(1)} KiB)`);
